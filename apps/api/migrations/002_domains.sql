CREATE TABLE integrations (
  uid CHAR(36) PRIMARY KEY,
  business_uid CHAR(36) NOT NULL,
  external_id VARCHAR(191),
  source ENUM('demo','import','live') NOT NULL DEFAULT 'demo',
  amount DECIMAL(18,2),
  currency CHAR(3) NOT NULL DEFAULT 'GEL',
  source_at DATETIME(3),
  synced_at DATETIME(3),
  payload JSON NOT NULL,
  created_at TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP(3),
  updated_at TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY external_dedup (business_uid,source,external_id),
  INDEX business_time (business_uid,source_at),
  FOREIGN KEY (business_uid) REFERENCES businesses(uid) ON DELETE CASCADE
);
